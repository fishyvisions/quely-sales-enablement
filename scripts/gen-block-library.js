function grab(src, field) {
  var pats = [
    new RegExp(field + "\\s*:\\s*'((?:\\\\.|[^'])*)'"),
    new RegExp(field + '\\s*:\\s*"((?:\\\\.|[^"])*)"'),
    new RegExp(field + "[^\\n]*\\?\\?\\s*'((?:\\\\.|[^'])*)'"),
    new RegExp(field + '[^\\n]*\\?\\?\\s*"((?:\\\\.|[^"])*)"')
  ];
  for (var i = 0; i < pats.length; i++) {
    var m = src.match(pats[i]);
    if (m) return m[1]
      .replace(/\\'/g, "'").replace(/\\"/g, '"').replace(/\\n/g, ' ')
      .replace(/\\u([0-9a-fA-F]{4})/g, function (_, h) { return String.fromCharCode(parseInt(h, 16)); });
  }
  return '';
}

function jsstr(s) { return JSON.stringify(s || ''); }

var out = [];
out.push('/* AUTO-GENERATED by scripts/gen-block-library.js from the v3 design blocks.');
out.push('   The app\'s catalog of reusable blocks: key, slug, role, label, editable');
out.push('   copy defaults. Re-run the generator after a design refresh. */');
out.push("'use strict';\n");
out.push('const BLOCKS = [');
BLOCKS.forEach(function (b) {
  var src = fs.readFileSync(path.join(SRC, b.file + '.dc.html'), 'utf8');
  var f = { eyebrow: grab(src, 'eyebrow'), headline: grab(src, 'headline'), body: grab(src, 'body') };
  out.push('  { key:' + jsstr(b.key) + ', slug:' + jsstr(b.slug) + ', role:' + jsstr(b.role) + ', label:' + jsstr(b.label) + ',');
  out.push('    fields: { eyebrow:' + jsstr(f.eyebrow) + ', headline:' + jsstr(f.headline) + ', body:' + jsstr(f.body) + ' } },');
});
out.push('];\n');
out.push([
  'const BY_KEY = {}; const BY_SLUG = {};',
  'BLOCKS.forEach(function (b) { BY_KEY[b.key] = b; BY_SLUG[b.slug] = b; });',
  '// Rule sets may reference a hero key with no servable block; map to a real one.',
  "const KEY_ALIAS = { scatter: 'collision' };",
  'function resolveKey(key) { return KEY_ALIAS[key] || key; }',
  'function get(key) { return BY_KEY[resolveKey(key)] || null; }',
  'function editableFields(entry) {',
  '  const f = (entry && entry.fields) || {};',
  "  return ['eyebrow', 'headline', 'body'].filter(function (k) { return f[k] && f[k].length; });",
  '}',
  'module.exports = { BLOCKS: BLOCKS, BY_KEY: BY_KEY, BY_SLUG: BY_SLUG, KEY_ALIAS: KEY_ALIAS, resolveKey: resolveKey, get: get, editableFields: editableFields };'
].join('\n'));

fs.writeFileSync(path.join(__dirname, '..', 'server', 'block-library.js'), out.join('\n') + '\n');
console.log('wrote server/block-library.js with', BLOCKS.length, 'blocks');
